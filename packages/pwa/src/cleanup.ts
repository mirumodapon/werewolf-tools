import type { Plugin } from 'vite-plus'

/** Served next to sw.js and loaded with importScripts. */
export const CLEANUP_SCRIPT = 'sw-cleanup.js'

/**
 * Deletes precaches that older builds left at exactly this worker's scope. Workbox's own
 * `cleanupOutdatedCaches` matches any cache name *containing* the scope, so home (`/`)
 * would wipe `/deal/`'s cache; matching the end of the name keeps nested apps safe.
 */
export function cleanupScript(cacheId: string): string {
  return `// Generated by @werewolf/pwa: remove older precaches at this exact scope.
self.addEventListener('activate', function (event) {
  var own = ${JSON.stringify(`${cacheId}-precache-`)}
  event.waitUntil(
    caches.keys().then(function (names) {
      var scope = self.registration.scope
      return Promise.all(
        names
          .filter(function (n) {
            return n.indexOf('-precache-') !== -1 && n.slice(-scope.length - 1) === '-' + scope && n.indexOf(own) !== 0
          })
          .map(function (n) {
            return caches.delete(n)
          }),
      )
    }),
  )
})
`
}

export function swCleanupPlugin(cacheId: string): Plugin {
  return {
    name: 'werewolf:sw-cleanup',
    apply: 'build',
    generateBundle() {
      this.emitFile({ type: 'asset', fileName: CLEANUP_SCRIPT, source: cleanupScript(cacheId) })
    },
  }
}
